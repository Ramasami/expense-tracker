import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = "docs/AI_CONTEXT.generated.md";
const args = new Set(process.argv.slice(2));
const staged = args.has("--staged");
const git = (...parts) =>
  execFileSync("git", parts, { cwd: root, maxBuffer: 20 * 1024 * 1024 });
const allowed = (name) =>
  name !== output &&
  (/^(app|lib|tests|scripts|public|apps-script|docs|\.github|\.githooks)\//.test(
    name,
  ) ||
    [
      "README.md",
      "AGENTS.md",
      "skills.MD",
      "package.json",
      "package-lock.json",
      "next.config.ts",
      "playwright.config.ts",
      "tsconfig.json",
    ].includes(name));
function generate() {
  const listed = git(
    "ls-files",
    "-z",
    "--cached",
    ...(staged ? [] : ["--others", "--exclude-standard"]),
  )
    .toString()
    .split("\0")
    .filter(Boolean);
  const files = [...new Set(listed)]
    .filter(allowed)
    .filter((name) => staged || fs.existsSync(path.join(root, name)))
    .sort();
  const sources = new Map();
  const hash = createHash("sha256");
  for (const name of files) {
    const buffer = staged
      ? git("show", ":" + name)
      : fs.readFileSync(path.join(root, name));
    hash.update(name).update("\0").update(buffer).update("\0");
    sources.set(name, buffer.toString("utf8"));
  }
  const pkg = JSON.parse(sources.get("package.json"));
  const screens = [
    ...(sources.get("lib/screen-guides.ts") || "")
      .split("export const screenGuides")
      .slice(1)
      .join("export const screenGuides")
      .matchAll(/^  (?:"([^"]+)"|([A-Za-z][A-Za-z ]*)): \{/gm),
  ].map((m) => m[1] || m[2]);
  const rows = (prefix) =>
    [...sources]
      .filter(
        ([name]) => name.startsWith(prefix) && /\.(tsx?|mjs|gs)$/.test(name),
      )
      .map(([name, text]) => {
        const exports = [
          ...text.matchAll(
            /\bexport\s+(?:default\s+)?(?:async\s+)?(?:function|class|const|type|interface)\s+([A-Za-z_$][\w$]*)/g,
          ),
        ].map((m) => m[1]);
        return `| [${name}](../${name}) | ${text.split("\n").length} | ${exports.length ? exports.map((value) => "`" + value + "`").join(", ") : "Module / component implementation"} |`;
      })
      .join("\n");
  const table = (prefix) =>
    "| Source | Lines | Exports / entry points |\n| --- | ---: | --- |\n" +
    rows(prefix);
  const tests = [...sources.keys()].filter(
    (name) => name.startsWith("tests/") && /\.(test|spec)\.ts$/.test(name),
  );
  return `# Budget Tracker — generated AI context\n\n<!-- Generated by scripts/update-ai-docs.mjs. Do not edit manually. -->\n\nSource fingerprint (SHA-256): \`${hash.digest("hex")}\`\n\nThis deterministic inventory reflects the current ${staged ? "staged source" : "source"} files. Read [the maintainer playbook](../skills.MD), [architecture](ARCHITECTURE.md) and [README](../README.md) for behavioral rules. This inventory does not include runtime credentials, Sheet data or receipt bytes. It is not an automatically inferred business changelog.\n\n## Stack and boundaries\n\n- Static Next.js ${pkg.dependencies.next} / React ${pkg.dependencies.react}; GitHub Pages.\n- Google OAuth + private Sheet authority; shared Apps Script receipt/AI service.\n- Read-only offline cache; confirmed financial writes use audit receipts and readback.\n- Release version comes from the shared version script, not package.json's initial version.\n- AI uploads produce reviewed proposals; keys stay in server-side Script properties.\n\n## Screens with guides\n\n${screens.map((name) => "- " + name).join("\n")}\n\n## Commands\n\n| npm script | Command |\n| --- | --- |\n${Object.entries(
    pkg.scripts,
  )
    .map(
      ([name, command]) =>
        "| `" + name + "` | `" + String(command).replaceAll("|", "\\|") + "` |",
    )
    .join(
      "\n",
    )}\n\n## UI modules\n\n${table("app/")}\n\n## Finance and integration modules\n\n${table("lib/")}\n\n## Server service\n\n${table("apps-script/")}\n\n## Automation scripts\n\n${table("scripts/")}\n\n## Test inventory\n\n${tests.map((name) => "- [" + name + "](../" + name + ")").join("\n")}\n\n## Documentation maintenance\n\nThe dev watcher refreshes this file after relevant source changes. Builds refresh it before compilation. The pre-commit hook regenerates it from staged content and stages only this generated file. CI checks for drift. Keep README and architecture prose accurate when behavior changes; the inventory cannot explain a new rule by itself.\n`.replace(
    "current staged source files",
    "current source files",
  );
}
function update() {
  // Staged and working snapshots must use identical prose for the same source.
  const content = generate().replace(
    "current staged source files",
    "current source files",
  );
  const target = path.join(root, output);
  const previous = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (args.has("--check")) {
    if (content !== previous) {
      console.error(
        "AI context is stale. Run npm run docs:sync and commit the generated file.",
      );
      process.exitCode = 1;
    } else console.log("AI context is current.");
    return;
  }
  if (content !== previous) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
    console.log("Updated " + output);
  }
  if (args.has("--stage")) git("add", "--", output);
}
update();
if (args.has("--watch")) {
  let timer;
  const schedule = (event, filename) => {
    if (
      filename &&
      String(filename).replaceAll("\\", "/").endsWith("AI_CONTEXT.generated.md")
    )
      return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        update();
      } catch (error) {
        console.error("Documentation refresh failed: " + error.message);
      }
    }, 200);
  };
  for (const dir of [
    "app",
    "lib",
    "tests",
    "scripts",
    "public",
    "apps-script",
    ".github",
    ".githooks",
    "docs",
  ]) {
    if (fs.existsSync(path.join(root, dir)))
      fs.watch(path.join(root, dir), { recursive: true }, schedule);
  }
  fs.watch(root, (event, filename) => {
    if (
      filename &&
      allowed(String(filename)) &&
      !String(filename).includes("/")
    )
      schedule(event, filename);
  });
  console.log("Watching project documentation sources.");
}
